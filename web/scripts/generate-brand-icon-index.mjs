#!/usr/bin/env node
// Generate src/assets/brand-icons/icons.ts — a static import map for every
// vendored brand icon (dark + light). Run after fetch-brand-icons.mjs.
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ICONS_DIR = join(ROOT, 'src/assets/brand-icons/icons')
const OUT_FILE = join(ROOT, 'src/assets/brand-icons/icons.ts')

function toCamelCase(key) {
  const parts = key.split('-')
  return (
    parts[0] +
    parts
      .slice(1)
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('')
  )
}

const light = readdirSync(join(ICONS_DIR, 'light'))
  .filter((f) => f.endsWith('.png'))
  .map((f) => f.replace(/\.png$/, ''))
const dark = readdirSync(join(ICONS_DIR, 'dark'))
  .filter((f) => f.endsWith('.png'))
  .map((f) => f.replace(/\.png$/, ''))

const keys = [...new Set([...light, ...dark])].sort()

const lines = []
lines.push(
  '// AUTO-GENERATED by scripts/generate-brand-icon-index.mjs — do not edit by hand.'
)
lines.push(
  '// Maps normalized brand icon keys to locally vendored dark/light PNGs,'
)
lines.push(
  '// replacing the registry.npmmirror.com CDN (blocked by the production CSP).'
)
lines.push('')
for (const key of keys) {
  lines.push(`import ${toCamelCase(key)}Dark from './icons/dark/${key}.png'`)
  lines.push(`import ${toCamelCase(key)}Light from './icons/light/${key}.png'`)
}
lines.push('')
lines.push('export type BrandIconVariant = "dark" | "light"')
lines.push('')
lines.push(
  'export const BRAND_ICONS: Record<string, Record<BrandIconVariant, string>> = {'
)
for (const key of keys) {
  lines.push(
    `  '${key}': { dark: ${toCamelCase(key)}Dark, light: ${toCamelCase(key)}Light },`
  )
}
lines.push('}')
lines.push('')

writeFileSync(OUT_FILE, lines.join('\n'))
console.log(
  `generated ${OUT_FILE} with ${keys.length} icons (${keys.length * 2} imports)`
)
